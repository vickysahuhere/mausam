export function translateText(locale: SupportedLocale, key: string): string {
  const cleanKey = key.trim().toLowerCase();
  const mappedKey = TITLE_ALIAS_MAP[cleanKey] || key;
  return TRANSLATIONS[locale]?.[mappedKey] ?? TRANSLATIONS[locale]?.[key] ?? TRANSLATIONS.en[mappedKey] ?? TRANSLATIONS.en[key] ?? key;
}
